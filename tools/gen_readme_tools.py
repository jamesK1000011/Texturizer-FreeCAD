"""Rewrite the tool list in README.md from texturizer/data/tools.json.

The block between the markers below is generated; edit the tool definitions,
not the block. Reads only the JSON, so it needs neither FreeCAD nor Agent Link.

    python3 tools/gen_readme_tools.py          # rewrite README.md
    python3 tools/gen_readme_tools.py --check  # exit 1 if it is out of date
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BEGIN = "<!-- tools:begin (generated by tools/gen_readme_tools.py) -->"
END = "<!-- tools:end -->"
SOURCE = os.path.join("texturizer", "data", "tools.json")


def _short(desc, limit=150):
    """The first sentence, without its argument details in brackets."""
    s = desc
    for _ in range(3):
        s = re.sub(r"\s*\([^()]*\)", "", s)
        s = re.sub(r"\s*\{[^{}]*\}", "", s)
    s = re.split(r"(?<=[.!?])\s", s.strip(), maxsplit=1)[0].strip().rstrip(".;,:")
    if len(s) > limit:
        s = s[:limit].rsplit(" ", 1)[0].rstrip(",;:") + " …"
    s = s.replace("|", "\\|")
    return s if s.endswith("…") else s + "."


def read():
    with open(os.path.join(ROOT, SOURCE), encoding="utf-8") as f:
        entries = json.load(f)["entries"]
    return [(name, e.get("group", ""), e.get("description", "")) for name, e in entries.items()]


def block():
    rows = ["| Tool | Group | What it does |", "|---|---|---|"]
    for name, group, desc in read():
        rows.append(f"| `{name}` | {group} | {_short(desc)} |")
    return "\n".join([BEGIN, *rows, END])


def render(text):
    i, j = text.find(BEGIN), text.find(END)
    if i < 0 or j < i:
        raise SystemExit("README.md has no tools block (markers missing)")
    return text[:i] + block() + text[j + len(END):]


def main(argv):
    readme = os.path.join(ROOT, "README.md")
    with open(readme, encoding="utf-8") as f:
        old = f.read()
    new = render(old)
    if "--check" in argv:
        if new != old:
            print("README.md tool list is out of date: run python3 tools/gen_readme_tools.py")
            return 1
        return 0
    if new != old:
        with open(readme, "w", encoding="utf-8") as f:
            f.write(new)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
